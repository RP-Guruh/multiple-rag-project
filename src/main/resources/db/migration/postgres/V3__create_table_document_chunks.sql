-- 1. Enable pgvector extension
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Table: document_chunks
-- Stores fragmented document text and vector embeddings ready for AI chatbot retrieval.
-- Note: 'vector' without fixed dimensions allows dynamic dimension models 
-- (e.g. 768 for nomic-embed-text, 1536 for text-embedding-3-small).
CREATE TABLE document_chunks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    project_id      BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    chunk_index     INT NOT NULL,
    content         TEXT NOT NULL,
    token_count     INT NOT NULL DEFAULT 0,
    embedding       vector,
    metadata        TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3. Standard Relational Indexes
CREATE INDEX idx_document_chunks_document_id ON document_chunks(document_id);
CREATE INDEX idx_document_chunks_project_id ON document_chunks(project_id);

-- 4. Cosine Similarity Index for retrieval
CREATE INDEX idx_document_chunks_embedding_hnsw 
ON document_chunks 
USING hnsw (embedding vector_cosine_ops)
WITH (m = 16, ef_construction = 64);

